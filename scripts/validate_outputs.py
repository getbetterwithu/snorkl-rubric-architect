#!/usr/bin/env python3
"""
validate_outputs.py - Automated Deliverable & Cross-File Consistency Validator (v15.0)

Mandatory pre-delivery gate before Step 5 completion can be declared.
Checks:
  1. Card PNG (`_문제등록화면.png`): exists, valid PNG IHDR, exact `2000 x 1000` px.
  2. Snorkl Plain-Text Markdown (`_정답_평가기준.md`):
     - UTF-8 readable, non-empty
     - Zero `$` characters and zero LaTeX commands (`\\frac`, `\\overline`, `\\triangle`, ...)
     - Zero Olympiad area bracket notation (`[△ABC]`, `[삼각형 ABC]`)
     - Zero fractional `0.5점` AI grading instructions (Snorkl AI uses 0-4 integer scale)
     - Required Snorkl rubric sections present
  3. Teacher Reference PDF (`_교사참고용_채점기준표.pdf`):
     - Valid `%PDF-` header, non-trivial size
     - Exact page count `1 <= pages <= max_pdf_pages` (default `1` page; uses PyMuPDF if
       installed, with a pure-Python PDF `/Type /Page` fallback)
     - Zero leaked `$` or `.katex-error` text in PDF pages (when PyMuPDF is available)
  4. Cross-File Consistency & Freshness (when source HTML files are present):
     - Timestamp ordering: `card_png >= card_html` and `sheet_pdf >= max(sheet_html, card_png)`
     - Spec hash match (`snorkl-spec-sha256` meta tag) if generated by `snorkl_builder.py`
     - Stem numeric literal consistency between `card_html` problem body and `.md` `[문항]`
     - Final answer consistency between `.md` `[정답]` and `sheet_html`
     - Headless DOM render audit (`data-render-status="ok"`, no overflow, no broken images)
"""

from __future__ import annotations

import argparse
import html as html_lib
import os
import pathlib
import re
import shutil
import sys
import tempfile
import unicodedata

from render_card import (
    audit_dom_headless,
    ensure_utf8_stdio,
    find_browser,
    prepare_resolved_html,
    read_png_dimensions,
)

FORBIDDEN_LATEX_PATTERNS = [
    r"\$",
    r"\\frac\b",
    r"\\overline\b",
    r"\\triangle\b",
    r"\\angle\b",
    r"\\square\b",
    r"\\sim\b",
    r"\\parallel\b",
    r"\\perp\b",
    r"\\sqrt\b",
    r"\\cdot\b",
    r"\\times\b",
    r"\\div\b",
    r"\\le\b",
    r"\\ge\b",
    r"\\neq\b",
    r"\\pm\b",
    r"\\therefore\b",
    r"\\because\b",
    r"\\mathrm\b",
    r"\\text\b",
    r"\\left\b",
    r"\\right\b",
    r"\\begin\b",
]

OLYMPIAD_AREA_BRACKET_RE = re.compile(r"\[\s*(?:△|∆|\\triangle\s*|삼각형\s*)[A-Za-z가-힣0-9]+\s*\]")


def count_pdf_pages_pure_python(pdf_path: str) -> int | None:
    """Count PDF pages without third-party dependencies (works on Chromium/Edge PDFs)."""
    try:
        with open(pdf_path, "rb") as f:
            raw = f.read()
    except OSError:
        return None
    if not raw.startswith(b"%PDF-"):
        return None
    # Match `/Type /Page` dictionary entries (excluding `/Type /Pages`)
    page_matches = re.findall(rb"/Type\s*/Page(?![A-Za-z])", raw)
    if page_matches:
        return len(page_matches)
    count_matches = [int(m) for m in re.findall(rb"/Type\s*/Pages\b[^>]*?/Count\s+(\d+)", raw, flags=re.DOTALL)]
    return max(count_matches) if count_matches else None


def inspect_pdf(pdf_path: str) -> tuple[int | None, str | None]:
    """Return `(page_count, extracted_text_or_none)`. Uses PyMuPDF if available, else pure Python."""
    try:
        import pymupdf  # type: ignore

        doc = pymupdf.open(pdf_path)
        try:
            pages = len(doc)
            full_text = "\n".join(doc[i].get_text() for i in range(pages))
            return pages, full_text
        finally:
            doc.close()
    except ImportError:
        return count_pdf_pages_pure_python(pdf_path), None
    except Exception:
        return None, None


def _strip_html_tags(fragment: str) -> str:
    no_scripts = re.sub(r"<(script|style|svg)\b[^>]*>.*?</\1>", " ", fragment, flags=re.DOTALL | re.IGNORECASE)
    no_tags = re.sub(r"<[^>]+>", " ", no_scripts)
    unescaped = html_lib.unescape(no_tags)
    return unicodedata.normalize("NFKC", unescaped)


def extract_numbers(text: str) -> set[str]:
    norm = unicodedata.normalize("NFKC", text)
    # Remove LaTeX command names so nothing interferes with numeric literals
    norm = re.sub(r"\\[A-Za-z]+", " ", norm)
    nums = set()
    for token in re.findall(r"\d+(?:\.\d+)?", norm):
        # Canonicalize e.g. 07 -> 7 while keeping decimals
        if "." in token:
            nums.add(str(float(token)).rstrip("0").rstrip(".") if float(token).is_integer() else str(float(token)))
        else:
            nums.add(str(int(token)))
    return nums


def extract_md_section(md_text: str, header_prefix: str) -> str:
    lines = md_text.splitlines()
    collecting = False
    buf: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if stripped.startswith(header_prefix):
                collecting = True
                continue
            if collecting:
                break
        if collecting:
            buf.append(line)
    return "\n".join(buf).strip()


def extract_card_stem_text(card_html_text: str) -> str:
    """Extract only problem stem blocks from card.html (excluding `.category-tag` and SVG)."""
    chunks: list[str] = []
    for cls in ("problem-header", "problem-formula", "target-question", "condition-text"):
        for m in re.finditer(
            rf'<div[^>]*class="[^"]*\b{cls}\b[^"]*"[^>]*>(.*?)</div>',
            card_html_text,
            flags=re.DOTALL | re.IGNORECASE,
        ):
            chunks.append(_strip_html_tags(m.group(1)))
    return "\n".join(chunks).strip()


def normalize_answer_str(ans: str) -> str:
    s = unicodedata.normalize("NFKC", ans).strip()
    s = s.replace("−", "-")
    s = re.sub(r"\s+", " ", s)
    return s


def validate_deliverable_set(
    png_path: str,
    md_path: str,
    pdf_path: str,
    card_html_path: str | None = None,
    sheet_html_path: str | None = None,
    max_pdf_pages: int = 1,
    check_dom: bool = True,
) -> tuple[bool, list[str]]:
    errors: list[str] = []

    # 1. Validate Card PNG (`2000 x 1000`)
    if not os.path.isfile(png_path):
        errors.append(f"Card PNG missing: {png_path}")
    else:
        dims = read_png_dimensions(png_path)
        if dims is None:
            errors.append(f"Card PNG is not a valid PNG file: {png_path}")
        elif dims != (2000, 1000):
            errors.append(f"Card PNG dimensions must be 2000x1000, got {dims[0]}x{dims[1]}: {png_path}")

    # 2. Validate Snorkl Plain-Text Markdown (`.md`)
    md_text = ""
    if not os.path.isfile(md_path):
        errors.append(f"Snorkl Markdown missing: {md_path}")
    else:
        try:
            with open(md_path, "r", encoding="utf-8") as f:
                md_text = f.read()
        except UnicodeDecodeError as e:
            errors.append(f"Snorkl Markdown is not valid UTF-8: {e}")

        if not md_text.strip():
            errors.append("Snorkl Markdown is empty.")
        else:
            for pat in FORBIDDEN_LATEX_PATTERNS:
                m = re.search(pat, md_text)
                if m:
                    errors.append(f"Forbidden LaTeX token `{m.group(0)}` leaked into Snorkl plain-text MD.")
                    break

            if OLYMPIAD_AREA_BRACKET_RE.search(md_text):
                errors.append("Forbidden Olympiad area bracket notation `[△ABC]` found in Snorkl MD.")

            # Snorkl AI only supports 0-4 integers; block instructions telling AI to award 0.5 points
            for line in md_text.splitlines():
                if "0.5점" in line and not any(
                    neg in line for neg in ("부여하지", "사용하지", "강제하지", "금지", "아닌")
                ):
                    errors.append(
                        f"Fractional `0.5점` AI scoring instruction found in MD (`{line.strip()}`); "
                        "Snorkl AI Explanation Score supports integer 0-4 only."
                    )
                    break

            required_markers = ["[문항]", "[정답", "[기본 모범 풀이", "채점 기준", "가드레일"]
            for marker in required_markers:
                if marker not in md_text:
                    errors.append(f"Required section `{marker}` missing from Snorkl MD.")

    # 3. Validate Teacher Reference PDF
    if not os.path.isfile(pdf_path):
        errors.append(f"Teacher PDF missing: {pdf_path}")
    else:
        size = os.path.getsize(pdf_path)
        if size < 1024:
            errors.append(f"Teacher PDF is abnormally small ({size} bytes): {pdf_path}")
        else:
            page_count, pdf_text = inspect_pdf(pdf_path)
            if page_count is None or page_count < 1:
                errors.append(f"Teacher PDF could not be parsed or has 0 pages: {pdf_path}")
            elif page_count > max_pdf_pages:
                errors.append(
                    f"Teacher PDF exceeded page limit: got {page_count} page(s), max allowed is {max_pdf_pages}."
                )
            if pdf_text is not None:
                if not pdf_text.strip():
                    errors.append("Teacher PDF text layer is completely empty.")
                if "$" in pdf_text:
                    errors.append("Unrendered `$` character detected in Teacher PDF text.")

    # 4. Cross-File Consistency, Timestamps, and DOM Render Audit
    md_stem = extract_md_section(md_text, "[문항") if md_text else ""
    md_answer = extract_md_section(md_text, "[정답") if md_text else ""

    card_sha = None
    sheet_sha = None
    browser = find_browser() if check_dom else None

    if card_html_path and os.path.isfile(card_html_path):
        with open(card_html_path, "r", encoding="utf-8") as f:
            card_html = f.read()

        if OLYMPIAD_AREA_BRACKET_RE.search(card_html):
            errors.append("Forbidden Olympiad area bracket notation `[△ABC]` found in Card HTML.")

        if os.path.isfile(png_path):
            if os.path.getmtime(png_path) + 1.0 < os.path.getmtime(card_html_path):
                errors.append(
                    "Card PNG is older than Card HTML — re-render `_문제등록화면.png` after editing Card HTML."
                )

        m_sha = re.search(r'<meta\s+name="snorkl-spec-sha256"\s+content="([^"]+)"', card_html)
        if m_sha:
            card_sha = m_sha.group(1)

        card_stem = extract_card_stem_text(card_html)
        if card_stem and md_stem:
            card_nums = extract_numbers(card_stem)
            md_nums = extract_numbers(md_stem)
            if card_nums != md_nums:
                errors.append(
                    f"Cross-file stem number mismatch between Card HTML ({sorted(card_nums)}) "
                    f"and Snorkl MD [문항] ({sorted(md_nums)})."
                )

        if browser:
            tdir = tempfile.mkdtemp(prefix="snorkl_val_card_")
            try:
                eff = prepare_resolved_html(os.path.abspath(card_html_path), tdir)
                ok_dom, msg = audit_dom_headless(browser, pathlib.Path(eff).as_uri(), 1000, 500, tdir)
                if not ok_dom:
                    errors.append(f"Card HTML DOM audit failed: {msg}")
            finally:
                shutil.rmtree(tdir, ignore_errors=True)

    if sheet_html_path and os.path.isfile(sheet_html_path):
        with open(sheet_html_path, "r", encoding="utf-8") as f:
            sheet_html = f.read()

        if OLYMPIAD_AREA_BRACKET_RE.search(sheet_html):
            errors.append("Forbidden Olympiad area bracket notation `[△ABC]` found in Sheet HTML.")

        if os.path.isfile(pdf_path):
            if os.path.getmtime(pdf_path) + 1.0 < os.path.getmtime(sheet_html_path):
                errors.append("Teacher PDF is older than Sheet HTML — re-render PDF after editing Sheet HTML.")
            if os.path.isfile(png_path) and os.path.getmtime(pdf_path) + 1.0 < os.path.getmtime(png_path):
                errors.append("Teacher PDF is older than Card PNG — re-render PDF so preview matches latest card.")

        m_sha = re.search(r'<meta\s+name="snorkl-spec-sha256"\s+content="([^"]+)"', sheet_html)
        if m_sha:
            sheet_sha = m_sha.group(1)

        m_ans = re.search(r'data-final-answer="([^"]*)"', sheet_html)
        if m_ans and md_answer:
            sheet_ans = normalize_answer_str(html_lib.unescape(m_ans.group(1)))
            md_ans_first = normalize_answer_str(md_answer.splitlines()[0])
            if sheet_ans != md_ans_first:
                errors.append(
                    f"Cross-file final answer mismatch between Snorkl MD (`{md_ans_first}`) "
                    f"and Teacher Sheet (`{sheet_ans}`)."
                )

        if browser:
            tdir = tempfile.mkdtemp(prefix="snorkl_val_sheet_")
            try:
                eff = prepare_resolved_html(os.path.abspath(sheet_html_path), tdir)
                ok_dom, msg = audit_dom_headless(browser, pathlib.Path(eff).as_uri(), 794, 1123, tdir)
                if not ok_dom:
                    errors.append(f"Teacher Sheet HTML DOM audit failed: {msg}")
            finally:
                shutil.rmtree(tdir, ignore_errors=True)

    if card_sha and sheet_sha and card_sha != sheet_sha:
        errors.append(
            f"Canonical ProblemSpec digest mismatch between Card HTML ({card_sha}) and Sheet HTML ({sheet_sha})."
        )

    return len(errors) == 0, errors


def _discover_paths_in_dir(directory: str, slug: str | None = None) -> tuple[str, str, str, str | None, str | None]:
    d = os.path.abspath(directory)
    if slug:
        png = os.path.join(d, f"{slug}_문제등록화면.png")
        md = os.path.join(d, f"{slug}_정답_평가기준.md")
        pdf = os.path.join(d, f"{slug}_교사참고용_채점기준표.pdf")
        c_html = os.path.join(d, f"{slug}_card.html")
        s_html = os.path.join(d, f"{slug}_sheet.html")
        return (
            png,
            md,
            pdf,
            c_html if os.path.isfile(c_html) else None,
            s_html if os.path.isfile(s_html) else None,
        )

    files = os.listdir(d)
    pngs = [os.path.join(d, f) for f in files if f.endswith("_문제등록화면.png")]
    mds = [os.path.join(d, f) for f in files if f.endswith("_정답_평가기준.md")]
    pdfs = [os.path.join(d, f) for f in files if f.endswith("_교사참고용_채점기준표.pdf")]
    if len(pngs) != 1 or len(mds) != 1 or len(pdfs) != 1:
        raise ValueError(
            f"Expected exactly 1 set of deliverables in {d}, found PNG={len(pngs)}, MD={len(mds)}, PDF={len(pdfs)}. "
            "Pass --slug <문제제목> to disambiguate."
        )
    inferred_slug = os.path.basename(pngs[0])[: -len("_문제등록화면.png")]
    c_html = os.path.join(d, f"{inferred_slug}_card.html")
    s_html = os.path.join(d, f"{inferred_slug}_sheet.html")
    return (
        pngs[0],
        mds[0],
        pdfs[0],
        c_html if os.path.isfile(c_html) else None,
        s_html if os.path.isfile(s_html) else None,
    )


def main(argv: list[str] | None = None) -> int:
    ensure_utf8_stdio()
    parser = argparse.ArgumentParser(description="Validate Snorkl Rubric Architect 3-file deliverable set.")
    parser.add_argument("target_dir", help="Directory containing generated deliverables")
    parser.add_argument("--slug", default=None, help="Problem filename prefix (optional if 1 set in folder)")
    parser.add_argument("--max-pages", type=int, default=1, help="Max allowed PDF pages (default: 1)")
    parser.add_argument("--skip-dom", action="store_true", help="Skip headless browser DOM audit")
    args = parser.parse_args(argv)

    try:
        png, md, pdf, c_html, s_html = _discover_paths_in_dir(args.target_dir, args.slug)
    except Exception as e:
        print(f"[Validator Error] {e}", file=sys.stderr)
        return 1

    ok, errors = validate_deliverable_set(
        png_path=png,
        md_path=md,
        pdf_path=pdf,
        card_html_path=c_html,
        sheet_html_path=s_html,
        max_pdf_pages=args.max_pages,
        check_dom=not args.skip_dom,
    )
    if ok:
        print(f"[Validator OK] All deliverables verified cleanly in: {os.path.abspath(args.target_dir)}")
        return 0

    print("[Validator FAILED] Deliverable verification errors:", file=sys.stderr)
    for err in errors:
        print(f"  - {err}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
